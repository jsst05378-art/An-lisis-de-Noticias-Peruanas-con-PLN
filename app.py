#  SECCIÓN: TÉCNICAS PLN
# ════════════════════════════════════════════════════════════════════════════════
if "Técnicas" in seccion:
    st.markdown('<p class="main-title">Técnicas PLN</p>', unsafe_allow_html=True)
    st.markdown('<p class="main-subtitle">Explicación y demostración de cada técnica aplicada</p>', unsafe_allow_html=True)

    tab1, tab2, tab3, tab4 = st.tabs(["🧹 Preprocesamiento", "📂 Clasificación", "😊 Sentimiento", "🏷️ NER"])

    with tab1:
        st.markdown("### Preprocesamiento de texto")
        st.markdown("""
        El preprocesamiento transforma el texto crudo en una representación limpia y estructurada.
        Las etapas aplicadas son:

        1. **Limpieza** — eliminar URLs, números, signos de puntuación
        2. **Tokenización** — dividir el texto en palabras individuales
        3. **Eliminación de stopwords** — quitar palabras sin valor semántico (artículos, preposiciones)
        4. **Lematización** — reducir palabras a su forma base mediante reglas de sufijos
        """)
        ejemplo = st.selectbox("Selecciona una noticia para ver el preprocesamiento:", df.titulo.tolist())
        row_ej = df[df.titulo == ejemplo].iloc[0]
        texto_ej = row_ej["titulo"] + ". " + row_ej.get("descripcion", "")
        prep_ej = preprocesar(texto_ej)

        col_p1, col_p2 = st.columns(2)
        with col_p1:
            st.markdown("**Texto original:**")
            st.info(texto_ej[:300])
            st.markdown("**Texto limpio:**")
            st.success(prep_ej["texto_limpio"][:300])
        with col_p2:
            st.markdown(f"**Tokens ({prep_ej['n_tokens']}):**")
            st.code(" | ".join(prep_ej["tokens"][:20]))
            st.markdown(f"**Sin stopwords ({prep_ej['n_palabras_utiles']}):**")
            st.code(" | ".join(prep_ej["tokens_sin_stopwords"][:20]))
            st.markdown("**Lemas:**")
            st.code(" | ".join(prep_ej["lemas"][:20]))

    with tab2:
        st.markdown("### Clasificación de texto")
        st.markdown("""
        Se aplica un **clasificador basado en diccionario de keywords** por categoría.
        Para cada noticia, se cuenta cuántas palabras clave de cada categoría aparecen
        en el título y la descripción, y se asigna la categoría con mayor score.

        **Categorías disponibles:** Política, Deportes, Economía, Seguridad, Clima, Internacional.
        """)
        # Matriz de confusión visual — distribución por categoría y fuente
        cat_fuente = df.groupby(["categoria","fuente"]).size().reset_index(name="n")
        fig_cf = px.bar(cat_fuente, x="categoria", y="n", color="fuente",
                        barmode="group", template="plotly_white",
                        color_discrete_sequence=["#C0392B","#2980B9"],
                        labels={"categoria":"Categoría","n":"Noticias","fuente":"Fuente"})
        fig_cf.update_layout(height=320, margin=dict(l=0,r=0,t=10,b=0))
        st.plotly_chart(fig_cf, use_container_width=True)

        st.markdown("**Keywords por categoría:**")
        for cat, kws in CATEGORIAS_KEYWORDS.items():
            st.markdown(f"- **{cat}:** {', '.join(kws[:8])}…")

    with tab3:
        st.markdown("### Análisis de sentimiento")
        st.markdown("""
        Se utiliza un **léxico de polaridad** con palabras positivas y negativas en español.
        El score se calcula como: `(positivas − negativas) / total_polarizadas`

        - Score > 0.15 → **Positivo**
        - Score < −0.15 → **Negativo**
        - Entre −0.15 y 0.15 → **Neutro**
        """)
        fig_box = px.box(df, x="sentimiento", y="score_sentimiento",
                         color="sentimiento", color_discrete_map=COLORES_SENT,
                         template="plotly_white",
                         labels={"sentimiento":"Sentimiento","score_sentimiento":"Score"})
        fig_box.update_layout(height=300, margin=dict(l=0,r=0,t=10,b=0), showlegend=False)
        st.plotly_chart(fig_box, use_container_width=True)

        st.markdown("**Distribución por categoría:**")
        sent_cat = df.groupby(["categoria","sentimiento"]).size().reset_index(name="n")
        fig_sc2 = px.bar(sent_cat, x="categoria", y="n", color="sentimiento",
                         barmode="stack", color_discrete_map=COLORES_SENT,
                         template="plotly_white",
                         labels={"categoria":"Categoría","n":"Noticias"})
        fig_sc2.update_layout(height=280, margin=dict(l=0,r=0,t=10,b=0))
        st.plotly_chart(fig_sc2, use_container_width=True)

    with tab4:
        st.markdown("### Reconocimiento de Entidades (NER)")
        st.markdown("""
        El NER identifica y clasifica menciones de **entidades nombradas** en el texto:

        - 👤 **PERSONA** — políticos, deportistas, periodistas
        - 🏛️ **ORGANIZACIÓN** — partidos, clubes, instituciones
        - 📍 **LUGAR** — ciudades, regiones, países

        Se implementa mediante un **gazeteer** (diccionario de entidades conocidas del contexto peruano)
        con búsqueda de subcadenas sobre el texto normalizado.
        """)
        all_ent = []
        for _, row in df.iterrows():
            for tipo, lista in row["entidades"].items():
                for e in lista:
                    all_ent.append({"Entidad": e, "Tipo": tipo, "Categoría noticia": row["categoria"]})
        df_ent = pd.DataFrame(all_ent)
        if not df_ent.empty:
            top_ent = df_ent.Entidad.value_counts().head(12).reset_index()
            top_ent.columns = ["Entidad","Menciones"]
            top_ent = top_ent.merge(df_ent[["Entidad","Tipo"]].drop_duplicates(), on="Entidad")
            TIPO_COLOR = {"PERSONA":"#E74C3C","ORGANIZACIÓN":"#2980B9","LUGAR":"#27AE60"}
            fig_ner = px.bar(top_ent, x="Menciones", y="Entidad", orientation="h",
                             color="Tipo", color_discrete_map=TIPO_COLOR,
                             template="plotly_white")
            fig_ner.update_layout(height=380, margin=dict(l=0,r=0,t=10,b=0))
            st.plotly_chart(fig_ner, use_container_width=True)

            st.markdown("**Tabla de entidades por noticia:**")
            tabla = df[["titulo","categoria","entidades"]].copy()
            tabla["Personas"] = tabla.entidades.apply(lambda e: ", ".join(e.get("PERSONA",[])))
            tabla["Organizaciones"] = tabla.entidades.apply(lambda e: ", ".join(e.get("ORGANIZACIÓN",[])))
            tabla["Lugares"] = tabla.entidades.apply(lambda e: ", ".join(e.get("LUGAR",[])))
            st.dataframe(tabla[["titulo","categoria","Personas","Organizaciones","Lugares"]].rename(columns={"titulo":"Título","categoria":"Categoría"}),
                         use_container_width=True, height=300)