def extraer_entidades(texto: str) -> dict:
    texto_lower = texto.lower()
    entidades = {"PERSONA": [], "ORGANIZACIÓN": [], "LUGAR": []}
    for p in PERSONAS:
        if p in texto_lower:
            entidades["PERSONA"].append(p.title())
    for o in ORGANIZACIONES:
        if o in texto_lower:
            entidades["ORGANIZACIÓN"].append(o.title())
    for l in LUGARES:
        if re.search(r"\b" + l + r"\b", texto_lower):
            entidades["LUGAR"].append(l.title())
    return {k: list(set(v)) for k, v in entidades.items()}

# ── Pipeline completo ────────────────────────────────────────────────────────────
def analizar_noticia(noticia: dict) -> dict:
    titulo  = noticia.get("titulo", "")
    desc    = noticia.get("descripcion", titulo)
    texto_completo = titulo + ". " + desc
    prep = preprocesar(texto_completo)
    cat  = clasificar_categoria(titulo, desc)
    sent = analizar_sentimiento(titulo, desc)
    ner  = extraer_entidades(texto_completo)
    palabras_freq = Counter(prep["tokens_sin_stopwords"]).most_common(6)
    return {**noticia, "categoria": cat, "sentimiento": sent["etiqueta"],
            "score_sentimiento": sent["score"],
            "palabras_pos": sent["positivas"], "palabras_neg": sent["negativas"],
            "entidades": ner,
            "n_entidades": sum(len(v) for v in ner.values()),
            "tokens_utiles": prep["n_palabras_utiles"],
            "palabras_freq": palabras_freq,
            "texto_limpio": prep["texto_limpio"]}

