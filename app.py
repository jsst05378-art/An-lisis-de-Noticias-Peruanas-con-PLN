if "Noticias" in seccion:
    st.markdown('<p class="main-title">Noticias analizadas</p>', unsafe_allow_html=True)
    st.markdown('<p class="main-subtitle">Filtros y detalle de cada noticia procesada</p>', unsafe_allow_html=True)

    col_f1, col_f2, col_f3 = st.columns(3)
    with col_f1:
        cats = ["Todas"] + sorted(df.categoria.unique().tolist())
        filtro_cat = st.selectbox("Categoría", cats)
    with col_f2:
        sents = ["Todos","Positivo","Neutro","Negativo"]
        filtro_sent = st.selectbox("Sentimiento", sents)
    with col_f3:
        fuentes = ["Todas"] + sorted(df.fuente.unique().tolist())
        filtro_fuente = st.selectbox("Fuente", fuentes)

    df_fil = df.copy()
    if filtro_cat   != "Todas":   df_fil = df_fil[df_fil.categoria == filtro_cat]
    if filtro_sent  != "Todos":   df_fil = df_fil[df_fil.sentimiento == filtro_sent]
    if filtro_fuente != "Todas":  df_fil = df_fil[df_fil.fuente == filtro_fuente]

    st.markdown(f"**{len(df_fil)} noticias**")

    for _, row in df_fil.iterrows():
        color_borde = COLORES_CAT.get(row["categoria"], "#ccc")
        tag_class   = {"Positivo":"tag-positivo","Negativo":"tag-negativo","Neutro":"tag-neutro"}.get(row["sentimiento"],"tag-neutro")
        ents_str = ""
        for tipo, lista in row["entidades"].items():
            if lista:
                ents_str += f"<span style='font-size:0.75rem;color:#555'>{tipo}: {', '.join(lista[:3])}</span><br>"
        st.markdown(f"""
        <div class="news-card" style="border-top-color:{color_borde}">
            <div class="news-title">{row['titulo']}</div>
            <div class="news-meta">
                📰 {row['fuente']} &nbsp;·&nbsp; 📅 {row['fecha']} &nbsp;·&nbsp;
                <span class="tag" style="background:{color_borde}22;color:{color_borde}">{row['categoria']}</span>
                <span class="tag {tag_class}">{row['sentimiento']}</span>
            </div>
            <br>{ents_str}
        </div>
        """, unsafe_allow_html=True)

